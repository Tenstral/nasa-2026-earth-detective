#!/usr/bin/env python3
"""
tools/build_fragments.py
========================
Build script that extracts inner HTML from report.html for the elements with id:
  - threeway
  - gldas
  - pairwise-differences
  - stakeholder-actions
  - limitations

And writes assets/js/report_fragments.js:
  window.REPORT_FRAGMENTS = { id: "<html>", ... };

Rules:
  - Single source of truth is report.html.
  - Strips <script> tags.
  - Strips inline event handlers (onclick, onchange, onload, etc.).
  - Strips/converts absolute asset paths to relative paths.
  - Cleanly escapes output for safe JavaScript embedding.
"""

import os
import re
import json
from html.parser import HTMLParser

ROOT_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REPORT_PATH = os.path.join(ROOT_DIR, 'report.html')
OUTPUT_PATH = os.path.join(ROOT_DIR, 'assets', 'js', 'report_fragments.js')

TARGET_IDS = [
    'threeway',
    'gldas',
    'pairwise-differences',
    'stakeholder-actions',
    'limitations'
]

def clean_html(html_str):
    # 1. Remove <script> tags and contents
    html_str = re.sub(r'<script\b[^>]*>[\s\S]*?<\/script>', '', html_str, flags=re.IGNORECASE)

    # 2. Remove inline event handlers (e.g. onclick="...", onchange="...")
    html_str = re.sub(r'\s+on[a-z]+\s*=\s*(["\'][^"\']*["\']|[^\s>]+)', '', html_str, flags=re.IGNORECASE)

    # 3. Clean absolute paths to relative paths
    # Replace file:///... or C:/.../outputs with relative outputs/
    html_str = re.sub(r'(?:file:///[^"\'>]*|/[a-zA-Z0-9_\-./]*|C:[^"\'>]*)(outputs/[^"\'>]+)', r'\1', html_str)
    # Also fix src="/outputs/..." to src="outputs/..."
    html_str = re.sub(r'src=["\']/(outputs/[^"\']+)["\']', r'src="\1"', html_str)
    # Also fix href="/index.html..." to href="index.html..."
    html_str = re.sub(r'href=["\']/(index\.html[^"\']*)["\']', r'href="\1"', html_str)

    return html_str.strip()

def extract_element_inner_html(html_content, element_id):
    # Match the opening tag of element with id="element_id"
    # e.g. <div id="threeway" ...> or <section class="..." id="threeway" ...>
    pattern = re.compile(rf'<([a-zA-Z0-9]+)\b[^>]*\bid=["\']{re.escape(element_id)}["\'][^>]*>', re.IGNORECASE)
    match = pattern.search(html_content)
    if not match:
        raise ValueError(f"Target element with id='{element_id}' not found in report.html")

    tag_name = match.group(1).lower()
    start_pos = match.end()

    # Track nested tags to find matching closing tag
    depth = 1
    pos = start_pos
    tag_regex = re.compile(rf'<\s*(/)?\s*{tag_name}\b[^>]*>', re.IGNORECASE)

    while depth > 0:
        next_tag = tag_regex.search(html_content, pos)
        if not next_tag:
            break
        is_closing = bool(next_tag.group(1))
        if is_closing:
            depth -= 1
            if depth == 0:
                inner_html = html_content[start_pos:next_tag.start()]
                return clean_html(inner_html)
        else:
            depth += 1
        pos = next_tag.end()

    raise ValueError(f"Could not find matching closing tag for <{tag_name} id='{element_id}'>")

def main():
    if not os.path.exists(REPORT_PATH):
        raise FileNotFoundError(f"report.html not found at {REPORT_PATH}")

    with open(REPORT_PATH, 'r', encoding='utf-8') as f:
        report_html = f.read()

    fragments = {}
    print(f"Extracting fragments from {REPORT_PATH}...")

    for fid in TARGET_IDS:
        inner = extract_element_inner_html(report_html, fid)
        char_len = len(inner)
        has_table = '<table' in inner.lower()
        print(f"  - [{fid}]: {char_len} characters, contains table: {has_table}")
        if char_len < 500:
            print(f"    WARNING: Fragment '{fid}' is under 500 characters ({char_len})")
        if not has_table:
            print(f"    WARNING: Fragment '{fid}' has no table")
        fragments[fid] = inner

    # Write output file
    os.makedirs(os.path.dirname(OUTPUT_PATH), exist_ok=True)
    with open(OUTPUT_PATH, 'w', encoding='utf-8') as f:
        f.write("/**\n")
        f.write(" * Auto-generated by tools/build_fragments.py from report.html\n")
        f.write(" * Single source of truth: report.html\n")
        f.write(" * Do not edit manually.\n")
        f.write(" */\n\n")
        f.write("(function () {\n")
        f.write("  'use strict';\n\n")
        f.write("  const REPORT_FRAGMENTS = ")
        f.write(json.dumps(fragments, indent=2, ensure_ascii=False))
        f.write(";\n\n")
        f.write("  if (typeof window !== 'undefined') {\n")
        f.write("    window.REPORT_FRAGMENTS = REPORT_FRAGMENTS;\n")
        f.write("  }\n")
        f.write("  if (typeof module !== 'undefined' && module.exports) {\n")
        f.write("    module.exports = REPORT_FRAGMENTS;\n")
        f.write("  }\n")
        f.write("})();\n")

    print(f"\nSuccessfully wrote {OUTPUT_PATH} ({os.path.getsize(OUTPUT_PATH):,} bytes).")

if __name__ == '__main__':
    main()
